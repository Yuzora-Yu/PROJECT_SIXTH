const toStats = (vector) =>
  Object.fromEntries(
    config.senses.map((k, i) => [k, Math.round(clamp(vector[i], 20, 100))]),
  );
export function validateProfileFeatures(f) {
  if (
    !f ||
    f.version !== profileRuleVersion ||
    !Object.hasOwn(numberVectors, f.life) ||
    !Number.isInteger(f.life)
  )
    throw Error("プロフィールを再計算してください。");
  if (f.mbti !== "" && !Object.hasOwn(mbtiNames, f.mbti))
    throw Error("タイプを確認してください。");
  if (
    !Array.isArray(f.signs) ||
    f.signs.length !== 10 ||
    f.signs.some((s) => s !== null && (!Number.isInteger(s) || s < 0 || s > 11))
  )
    throw Error("惑星配置を確認してください。");
  return {
    version: profileRuleVersion,
    life: f.life,
    mbti: f.mbti,
    signs: [...f.signs],
  };
}
export function calculateProfile(input) {
  const f = validateProfileFeatures(input),
    base = numberVectors[f.life];
  const mbtiDelta = Array(5).fill(0);
  for (const l of f.mbti)
    letterVectors[l].forEach((v, i) => (mbtiDelta[i] += v));
  const elements = [0, 0, 0, 0];
  f.signs.forEach((s, i) => {
    if (s !== null) elements[s % 4] += weights[i];
  });
  const total = elements.reduce((a, b) => a + b, 0);
  const planetDelta = Array.from({ length: 5 }, (_, i) =>
    total
      ? Math.round(
          (elements.reduce((sum, w, e) => sum + w * elementVectors[e][i], 0) /
            total) *
            2,
        )
      : 0,
  );
  const stats = toStats(base.map((v, i) => v + mbtiDelta[i] + planetDelta[i]));
  return {
    features: f,
    base: toStats(base),
    mbtiStats: toStats(base.map((v, i) => v + mbtiDelta[i])),
    stats,
    mbtiDelta,
    planetDelta,
    elements,
    bonus: Object.fromEntries(config.senses.map((k) => [k, stats[k] / 10])),
  };
}
