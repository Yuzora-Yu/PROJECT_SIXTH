export const numberVectors = Object.fromEntries(
  Object.entries(numberSeeds).map(([number, vector]) => {
    const mean = vector.reduce((sum, value) => sum + value, 0) / 5;
    return [
      number,
      vector.map((value) =>
        Math.round(clamp(mean + (value - mean) * 1.6, 20, 100)),
      ),
    ];
  }),
);
