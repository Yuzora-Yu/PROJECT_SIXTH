export function profileReading(model) {
  const f = model.features,
    n = numberReading[f.life],
    type = f.mbti;
  const style = type ? (type[1] === "N" ? "N" + type[2] : "S" + type[3]) : null;
  const dominant = model.elements.indexOf(Math.max(...model.elements));
  const numeric = `数秘${f.life}からは、「${n[0]}」という見立てになる。とりわけ、${n[1]}点に注目している。`;
  const opening =
    numeric +
    (type
      ? `MBTIの自己申告は${mbtiLabel(type)}。これを踏まえると、受け取った感触を${styleReading[style][0]}姿勢も加わる。${crossReading[f.life][["NT", "NF", "SJ", "SP"].indexOf(style)]}${typeReading[type]}`
      : "この見立てを、君自身の経験と照らし合わせたい。まず、どの場面を思い浮かべたか覚えておいてほしい。");
  const sun = f.signs[0],
    moon = f.signs[1];
  let sky = model.elements.some(Boolean)
    ? `惑星配置まで含めると、${elementNames[dominant]}の要素が最も強く表れている。この配置は、${elementReading[dominant]}傾向として読める。数秘で捉えた「${n[0]}」面が、実際の観測記録にも現れるか確かめたい。`
    : "惑星配置については、位置を確定できる情報がそろってから所見に加えよう。";
  sky +=
    sun !== null && moon !== null
      ? `太陽と月の関係を見ると、${moonPairs[sun % 4][moon % 4]}`
      : "太陽と月の関係は、出生時刻が分かれば、より詳しく読み取れる。";
  if (sun !== null)
    sky += [
      "試験を始めるときに得た感触を、配置との照合材料にしたい。",
      "しばらく観測したあとにも残る感触を、配置との照合材料にしたい。",
      "観測の途中で見方が変わった瞬間を、配置との照合材料にしたい。",
    ][sun % 3];
  let closing = "";
  if (type && f.signs[2] !== null) {
    const mercury = f.signs[2] % 4;
    closing = `水星の位置からは、「${["まず試して理解する", "具体的な違いから考える", "複数の説明を並べる", "感触を言葉へ移す"][mercury]}」傾向も読み取れる。${type[2] === "T" ? "筋道の通った答えを選ぶ前に、最初の違和感も記録してほしい。" : "感覚に合う答えと、観測で確かめた答えを並べ、その違いを見ておこう。"}`;
  }
  const highest = config.senses.reduce((a, b) =>
    model.stats[a] >= model.stats[b] ? a : b,
  );
  closing += `総合チャートでは、${config.labels[highest]}が最も強く出ている。現段階では得意分野と断定せず、今後の記録で再現性を確かめたい。一方で、${n[2]}可能性もある。${type ? styleReading[style][1] : "次の試行では、普段とは異なる見方を一つ選んでほしい。"}`;
  const paragraphs = [opening, sky, closing];
  return {
    title: `${n[0]}人`,
    numeric,
    paragraphs,
    short: paragraphs.join("\n\n"),
  };
}
